package com.retrohub.tv.saves

import java.io.File

/**
 * Per-profile RetroArch configuration (verified on RetroArch 1.22.2, com.retroarch.ra32):
 *
 *  - RetroHub writes  <root>/profiles/<id>/retroarch.cfg  and passes it as CONFIGFILE.
 *  - The managed keys come FIRST and the user's own config is `#include`d LAST. With the include
 *    first, the included file's values win and states land in RetroArch's default folder.
 *  - RetroArch does not rewrite this file on exit, so RetroHub fully owns it and regenerates it
 *    before every launch (that is how "Resume" vs "Start fresh" works).
 *  - savestate_auto_save writes <rom>.state.auto when content is closed from RetroArch's menu
 *    (Close Content / Quit). It is NOT written when the player presses Home and RetroArch is
 *    later replaced by a new launch.
 */
object ProfileConfig {

    /**
     * @param savesDir/statesDir null = keep RetroArch's own save folders (per-profile saves off).
     * @param exitCombo RetroArch gamepad combo that quits back to RetroHub (input_quit_gamepad_combo):
     *        0 off, 3 L1+R1+Start+Select, 7 hold Start, 8 hold Select.
     */
    fun build(
        savesDir: String?,
        statesDir: String?,
        autoLoad: Boolean,
        includeConfig: String?,
        exitCombo: Int = EXIT_HOLD_START,
    ): String = buildString {
        appendLine("# Generated by RetroHub TV before each launch. Edits here are overwritten.")
        appendLine("# Change RetroArch settings in RetroArch; they are stored in the included config.")
        if (savesDir != null && statesDir != null) {
            appendLine("savefile_directory = ${quote(savesDir)}")
            appendLine("savestate_directory = ${quote(statesDir)}")
            appendLine("savestate_auto_save = \"true\"")
            appendLine("savestate_auto_load = \"$autoLoad\"")
            appendLine("savestate_thumbnail_enable = \"true\"")
        }
        // Getting back to RetroHub (key names and values verified in RetroArch 1.22.2's retroarch.cfg):
        // Close Content quits RetroArch, so Android returns to RetroHub; the quit combo does the same
        // straight from gameplay. Both close the content properly, so the auto-save is written.
        appendLine("quit_on_close_content = \"1\"")
        appendLine("input_quit_gamepad_combo = \"$exitCombo\"")
        if (exitCombo != EXIT_OFF) appendLine("confirm_quit = \"false\"")
        val include = includeConfig?.trim().orEmpty()
        if (include.isNotEmpty()) appendLine("#include ${quote(include)}")
    }

    private fun quote(v: String) = "\"" + v.replace("\"", "") + "\""

    const val EXIT_OFF = 0
    const val EXIT_L1_R1_START_SELECT = 3
    const val EXIT_HOLD_START = 7
    const val EXIT_HOLD_SELECT = 8

    /** Choices offered in Settings, in display order. */
    val EXIT_CHOICES = listOf(
        EXIT_HOLD_START to "Hold Start (2 seconds)",
        EXIT_HOLD_SELECT to "Hold Select (2 seconds)",
        EXIT_L1_R1_START_SELECT to "L1 + R1 + Start + Select",
        EXIT_OFF to "Off (use Close Content only)",
    )

    fun exitLabel(combo: Int): String = EXIT_CHOICES.firstOrNull { it.first == combo }?.second ?: "Custom ($combo)"

    /** One-line instruction for getting back to RetroHub from a game. */
    fun exitHint(combo: Int): String =
        (if (combo != EXIT_OFF) "${exitLabel(combo).substringBefore(" (")} on your controller, or " else "") +
            "open RetroArch's menu (Start + Select by default) → Close Content"
}

data class SaveStateInfo(
    val file: File,
    /** -1 = auto (written on Close Content), 0..n = manual slot. */
    val slot: Int,
    val thumbnail: File?,
    val modified: Long,
) {
    val label: String get() = if (slot < 0) "Auto save" else "Slot $slot"
}

object SaveStates {
    /**
     * Slot for a RetroArch state file name, or null when it does not belong to [romBase].
     * "<base>.state" = slot 0, "<base>.state3" = slot 3, "<base>.state.auto" = auto.
     */
    fun slotOf(fileName: String, romBase: String): Int? {
        val prefix = "$romBase.state"
        if (!fileName.startsWith(prefix)) return null
        val rest = fileName.substring(prefix.length)
        return when {
            rest.isEmpty() -> 0
            rest == ".auto" -> -1
            rest.all { it.isDigit() } && rest.length <= 3 -> rest.toInt()
            else -> null
        }
    }

    /** RetroArch may sort states into per-core sub-folders, so look one level down too. */
    fun find(statesDir: File, romFileName: String): List<SaveStateInfo> {
        val base = romFileName.substringBeforeLast('.', romFileName)
        val dirs = listOf(statesDir) + (statesDir.listFiles()?.filter { it.isDirectory } ?: emptyList())
        val out = ArrayList<SaveStateInfo>()
        for (dir in dirs) {
            dir.listFiles()?.forEach { f ->
                if (!f.isFile || f.name.endsWith(".png")) return@forEach
                val slot = slotOf(f.name, base) ?: return@forEach
                val thumb = File(f.path + ".png").takeIf { it.isFile }
                out.add(SaveStateInfo(f, slot, thumb, f.lastModified()))
            }
        }
        return out.sortedWith(compareBy<SaveStateInfo> { it.slot >= 0 }.thenByDescending { it.modified })
    }

    /** Deletes every state (and thumbnail) of this game. Returns the number of files removed. */
    fun deleteAll(states: List<SaveStateInfo>): Int =
        states.sumOf { s -> listOfNotNull(s.file, s.thumbnail).count { it.delete() } }
}
